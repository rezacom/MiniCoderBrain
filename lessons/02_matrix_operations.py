"""درس ۲: ضرب ماتریسی، ضرب عضو به عضو و پخش خودکار."""

import torch


def main():
    left = torch.tensor([[1.0, 2.0], [3.0, 4.0]])  # شکل ۲×۲
    right = torch.tensor([[5.0], [6.0]])  # شکل ۲×۱

    # در ضرب ماتریسی، ابعاد داخلی باید برابر باشند: (۲×۲) @ (۲×۱) ← (۲×۱).
    product = left @ right
    print("شکل ورودی‌ها:", left.shape, right.shape)
    print("ضرب ماتریسی:\n", product)
    print("اولین خروجی = ۱×۵ + ۲×۶ =", product[0, 0].item())

    # ضرب عضو به عضو، هر جایگاه را فقط در جایگاه متناظر ضرب می‌کند.
    print("ضرب عضو به عضو:\n", left * left)

    # بردارِ دو عضوی روی هر سطر ماتریس پخش می‌شود؛ شکل خروجی ۲×۲ است.
    bias = torch.tensor([10.0, 20.0])
    print("پخش خودکارِ بردار روی سطرها:\n", left + bias)
    print("ترانهاده (جابجایی سطر و ستون):\n", left.T)

    print("در شبکهٔ عصبی، ضرب ماتریسی ورودی‌ها را با وزن‌ها ترکیب می‌کند؛")
    print("مثلاً دسته‌ای از ورودی‌ها را یکجا به خروجی‌های لایه تبدیل می‌کند.")


if __name__ == "__main__":
    main()
